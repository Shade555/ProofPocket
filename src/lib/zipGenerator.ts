import JSZip from "jszip";
import { Project } from "@/types";
import { sanitizeSafeFilename, validateZipEntryPath } from "./security";

export interface GeneratedPackResult {
  zipBuffer: Buffer;
  fileManifest: Array<{ path: string; sizeBytes: number; description: string }>;
  reports: {
    markdownChecklist: string;
    jsonReport: string;
    missingItemsReport: string;
    provenanceReport: string;
  };
}

/**
 * Builds the Markdown Checklist report.
 */
export function buildMarkdownChecklist(project: Project): string {
  const dateStr = new Date().toISOString().split("T")[0];
  const lines: string[] = [
    `# ProofPocket Application Pack Checklist`,
    `**Project**: ${project.name}`,
    `**Generated**: ${dateStr}`,
    `**Status**: ${project.status.toUpperCase()}`,
    project.deadline ? `**Application Deadline**: ${project.deadline}` : `**Application Deadline**: None specified`,
    ``,
    `> **Important Notice**: This checklist was generated by ProofPocket using open-weight AI assistance (Google Gemma) and deterministic document validation. ProofPocket does NOT certify document authenticity, official acceptance, or legal sufficiency. Always verify with official program guidelines before submission.`,
    ``,
    `## Summary`,
    `- **Total Requirements**: ${project.stats.totalRequirements}`,
    `- **Satisfied**: ${project.stats.satisfied}`,
    `- **Partially Satisfied**: ${project.stats.partiallySatisfied}`,
    `- **Needs Review**: ${project.stats.needsReview}`,
    `- **Missing**: ${project.stats.missing}`,
    `- **Estimated Manual Effort Saved**: ~${project.stats.estimatedTimeSavedMinutes} minutes`,
    ``,
    `---`,
    `## Requirement Verification Checklist`,
    ``,
  ];

  for (const req of project.requirements) {
    const match = project.matches.find((m) => m.requirementId === req.id);
    let checkSymbol = "[ ]";
    let statusLabel = "MISSING";
    if (req.status === "satisfied") {
      checkSymbol = "[x]";
      statusLabel = "SATISFIED";
    } else if (req.status === "partially_satisfied") {
      checkSymbol = "[-] ";
      statusLabel = "PARTIALLY SATISFIED";
    } else if (req.status === "needs_review") {
      checkSymbol = "[?]";
      statusLabel = "NEEDS REVIEW";
    }

    lines.push(`### ${checkSymbol} ${req.title} [${statusLabel}]`);
    lines.push(`- **Type**: ${req.documentType} | **Mandatory**: ${req.mandatory ? "Yes" : "Optional"}`);
    lines.push(`- **Description**: ${req.description}`);
    if (req.sourceQuote) {
      lines.push(`- **Source Instructions Quote**: _"${req.sourceQuote}"_`);
    }

    if (match && match.documentFilename) {
      lines.push(`- **Matched Document**: \`${match.documentFilename}\`${match.pageReference ? ` (Page ${match.pageReference})` : ""}`);
      lines.push(`- **Match Explanation**: ${match.explanation}`);
      if (match.supportingExcerpt) {
        lines.push(`- **Supporting Evidence Excerpt**:`);
        lines.push(`  > ${match.supportingExcerpt.replace(/\n/g, "\n  > ")}`);
      }
      if (match.missingFields && match.missingFields.length > 0) {
        lines.push(`- **Missing or Incomplete Details**: ${match.missingFields.join(", ")}`);
      }
      if (match.conflictingEvidence) {
        lines.push(`- **⚠️ Conflicting Evidence**: ${match.conflictingEvidence}`);
      }
    } else {
      lines.push(`- **Status**: No supporting document identified in uploaded pack.`);
      lines.push(`- **Required Evidence**: ${req.evidenceNeeded}`);
    }

    if (req.uncertaintyExplanation) {
      lines.push(`- **Agent Uncertainty Note**: ${req.uncertaintyExplanation}`);
    }

    lines.push(``);
  }

  return lines.join("\n");
}

/**
 * Builds the Missing Items & Action Plan report.
 */
export function buildMissingItemsReport(project: Project): string {
  const missingOrPending = project.requirements.filter(
    (r) => r.status === "missing" || r.status === "partially_satisfied" || r.status === "needs_review"
  );

  const lines: string[] = [
    `# ProofPocket Action Items & Missing Evidence Report`,
    `**Project**: ${project.name}`,
    `**Generated**: ${new Date().toISOString()}`,
    ``,
  ];

  if (missingOrPending.length === 0) {
    lines.push(`✅ **All requirements have satisfied status!**`);
    lines.push(`Please do a final manual check of the organized documents before submitting.`);
    return lines.join("\n");
  }

  lines.push(`The following ${missingOrPending.length} requirement(s) require applicant action before final submission:\n`);

  for (const req of missingOrPending) {
    const match = project.matches.find((m) => m.requirementId === req.id);
    lines.push(`## ⚠️ ${req.title} (${req.status.replace("_", " ").toUpperCase()})`);
    lines.push(`- **Requirement Importance**: ${req.mandatory ? "MANDATORY" : "Optional"}`);
    lines.push(`- **Evidence Required**: ${req.evidenceNeeded}`);

    if (req.status === "missing") {
      lines.push(`- **Action Required**: Upload a document for this requirement (e.g. ${req.documentType}).`);
    } else if (req.status === "partially_satisfied") {
      lines.push(`- **Current Coverage**: Only partial coverage found.`);
      if (match?.missingFields?.length) {
        lines.push(`- **Missing Items**: ${match.missingFields.join(", ")}`);
      }
      lines.push(`- **Action Required**: Provide the remaining documentation or updated credential.`);
    } else if (req.status === "needs_review") {
      lines.push(`- **Issue**: Ambiguous or unverified documentation detected.`);
      if (match?.conflictingEvidence) {
        lines.push(`- **Discrepancy**: ${match.conflictingEvidence}`);
      }
      lines.push(`- **Action Required**: Review the attached file \`${match?.documentFilename || "unknown"}\` or replace with an official registrar/issuer document.`);
    }
    lines.push(``);
  }

  return lines.join("\n");
}

/**
 * Builds the Provenance and Evidence Audit report.
 */
export function buildProvenanceReport(project: Project): string {
  const lines: string[] = [
    `# ProofPocket Provenance & Evidence Audit Trail`,
    `**Project**: ${project.name}`,
    `**Generated**: ${new Date().toISOString()}`,
    ``,
    `This report documents the extraction origin and evidence linkage for every document in this pack.`,
    ``,
    `---`,
    `## Documents Ingested`,
    ``,
  ];

  for (const doc of project.documents) {
    lines.push(`### 📄 ${doc.originalFilename}`);
    lines.push(`- **Internal Safe ID**: \`${doc.id}\``);
    lines.push(`- **Suggested Pack Filename**: \`${doc.suggestedFilename || doc.safeFilename}\``);
    lines.push(`- **MIME Type**: \`${doc.mimeType}\` (${Math.round(doc.sizeBytes / 1024)} KB)`);
    lines.push(`- **Extraction Method**: \`${doc.extractionMethod}\``);
    if (doc.pageCount) {
      lines.push(`- **Page Count**: ${doc.pageCount}`);
    }
    lines.push(`- **Extracted Fields**:`);
    for (const [key, field] of Object.entries(doc.extractedFields)) {
      lines.push(`  - **${key}**: "${field.value}" (Confidence: ${Math.round(field.confidence * 100)}%)`);
      if (field.evidenceSnippet) {
        lines.push(`    - _Evidence_: "${field.evidenceSnippet}"`);
      }
    }
    lines.push(``);
  }

  lines.push(`---`);
  lines.push(`## Requirement to Evidence Mapping`);
  lines.push(``);

  for (const match of project.matches) {
    const req = project.requirements.find((r) => r.id === match.requirementId);
    lines.push(`- **Requirement**: ${req?.title || match.requirementId}`);
    lines.push(`  - **Matched Document**: \`${match.documentFilename || "NONE"}\``);
    lines.push(`  - **Decision Status**: \`${match.status}\` (Confidence: \`${match.confidence}\`)`);
    lines.push(`  - **User Confirmation**: \`${match.userDecision}\``);
    if (match.supportingExcerpt) {
      lines.push(`  - **Snippet**: "${match.supportingExcerpt.replace(/\n/g, " ")}"`);
    }
    lines.push(``);
  }

  return lines.join("\n");
}

/**
 * Generates the safe, complete application pack ZIP archive.
 */
export async function generateApplicationPackZip(
  project: Project
): Promise<GeneratedPackResult> {
  const zip = new JSZip();
  const fileManifest: Array<{ path: string; sizeBytes: number; description: string }> = [];

  const markdownChecklist = buildMarkdownChecklist(project);
  const missingItemsReport = buildMissingItemsReport(project);
  const provenanceReport = buildProvenanceReport(project);

  const cleanProjectJson = {
    ...project,
    // Do not include huge fileBufferBase64 in JSON report
    documents: project.documents.map((d) => {
      // eslint-disable-next-line @typescript-eslint/no-unused-vars
      const { fileBufferBase64, ...rest } = d;
      return rest;
    }),
  };
  const jsonReport = JSON.stringify(cleanProjectJson, null, 2);

  const addZipFile = (relPath: string, content: string | Buffer, description: string) => {
    if (!validateZipEntryPath(relPath)) {
      throw new Error(`Unsafe ZIP entry path rejected: "${relPath}"`);
    }
    zip.file(relPath, content);
    const size = Buffer.isBuffer(content) ? content.length : Buffer.byteLength(content, "utf8");
    fileManifest.push({ path: relPath, sizeBytes: size, description });
  };

  // Add 4 core documentation reports
  addZipFile("APPLICATION_PACK_CHECKLIST.md", markdownChecklist, "Markdown checklist with requirements, statuses, and evidence quotes");
  addZipFile("APPLICATION_PACK_REPORT.json", jsonReport, "Machine-readable structured project report");
  addZipFile("MISSING_AND_ACTION_ITEMS.md", missingItemsReport, "Action items report highlighting missing documents and items needing review");
  addZipFile("PROVENANCE_AND_EVIDENCE_AUDIT.md", provenanceReport, "Provenance audit trail mapping extracted snippets to source files");

  // Add organized user documents
  const docsFolder = "documents";
  const usedFilenames = new Set<string>();

  for (let i = 0; i < project.documents.length; i++) {
    const doc = project.documents[i];
    let candidateName = doc.suggestedFilename
      ? sanitizeSafeFilename(doc.suggestedFilename)
      : sanitizeSafeFilename(doc.safeFilename || doc.originalFilename);

    if (usedFilenames.has(candidateName.toLowerCase())) {
      candidateName = `${i + 1}_${candidateName}`;
    }
    usedFilenames.add(candidateName.toLowerCase());

    const docZipPath = `${docsFolder}/${candidateName}`;

    let fileContent: Buffer;
    if (doc.fileBufferBase64) {
      fileContent = Buffer.from(doc.fileBufferBase64, "base64");
    } else {
      // Synthetic demo or placeholder text representation if buffer was cleared for memory
      fileContent = Buffer.from(
        `[ProofPocket Document Archive]\nOriginal Filename: ${doc.originalFilename}\nExtraction Method: ${doc.extractionMethod}\nExtracted Content:\n\n${doc.rawText}`,
        "utf8"
      );
    }

    addZipFile(docZipPath, fileContent, `Organized copy: ${doc.originalFilename}`);
  }

  const zipBuffer = await zip.generateAsync({
    type: "nodebuffer",
    compression: "DEFLATE",
    compressionOptions: { level: 9 },
  });

  return {
    zipBuffer,
    fileManifest,
    reports: {
      markdownChecklist,
      jsonReport,
      missingItemsReport,
      provenanceReport,
    },
  };
}
